  m
}

#' Uncorrected (CellRanger) counts for the cells of a processed object.
#'
#' The primary DE runs on uncorrected counts. CellBender is used for QC,
#' clustering, annotation and cross-cell-type specificity, not for DE
#' magnitudes. It over-corrects the reactive-astrocyte panel (SERPINA3, OSMR,
#' CHI3L1): it zeroes genuine low-level expression in PWoH while leaving it
#' high in PWH, which turns a quantitative difference
#' into artifactual complete separation. That both breaks edgeR's QL F-test
#' (negative F) and overstates the effect.
#'
#' This pulls the RAW assay for exactly the cells of `obj`, in exactly `obj`'s
#' cell order and gene set, so the caller can build an SCE from uncorrected
#' counts and run the published prepSCE -> aggregateData -> pbDS chain unchanged.
#'
#' Cell names are "<barcode>-<sample_ids>"; sample folders are resolved by
#' matching the sample_ids prefix against the directory listing rather than the
#' sheet's sample_name, because the corrected pipeline renamed directories
#' (1039_HIVOUD_INS -> 1039_HIV_INS) and the sheet still carries old names for
#' non-paper samples.
#' region = NULL uses the object's own `region` column per cell, which is what
#' the cross-region DE (07) needs: its cells come from the combined object and
#' span INS, PFC and VST, so no single region directory holds them all.
uncorrected_counts <- function(obj, region = NULL, verbose = TRUE) {
  stopifnot("sample_ids" %in% colnames(obj@meta.data))
  cells <- colnames(obj)
  sids  <- as.character(obj@meta.data$sample_ids)

  if (is.null(region)) {
    stopifnot("region" %in% colnames(obj@meta.data))
    regs <- toupper(as.character(obj@meta.data$region))
    if (verbose) message("[uncorrected] multi-region object: ",
                         paste(sprintf("%s=%d", names(table(regs)), table(regs)),
                               collapse = "  "))
    parts <- lapply(unique(regs), function(rg) {
      idx <- regs == rg
      uncorrected_counts(obj[, idx], region = rg, verbose = verbose)
    })
    mat <- do.call(cbind, parts)[, cells, drop = FALSE]
    stopifnot(identical(colnames(mat), colnames(obj)))
    return(mat)
  }
  region <- toupper(region)

  ## Cell names carry one of two suffix forms, depending on how far through the
  ## pipeline the object came:
  ##   "<barcode>-<sample_ids>"           regional 03 output
  ##   "<barcode>-<sample_ids>-<REGION>"  anything that passed through the
  ##                                      combined object (regional 04/05 subset
  ##                                      from seurat_combined_v3.RDS)
  ## Try the longer form first. Getting this wrong yields barcodes that match
  ## nothing, which is why the check below is fatal rather than a warning.
  suf_long  <- paste0("-", sids, "-", toupper(region))
  suf_short <- paste0("-", sids)
  ends_with <- function(x, s) substr(x, nchar(x) - nchar(s) + 1L, nchar(x)) == s

  use_long <- ends_with(cells, suf_long)
  use_short <- !use_long & ends_with(cells, suf_short)
  bad <- !use_long & !use_short
  if (any(bad))
    stop(sum(bad), " cell name(s) match neither -<sample_ids>-", toupper(region),
         " nor -<sample_ids>, e.g. ", cells[which(bad)[1]],
         " with sample_ids ", sids[which(bad)[1]])

  nsuf <- ifelse(use_long, nchar(suf_long), nchar(suf_short))
  bcs  <- substr(cells, 1L, nchar(cells) - nsuf)
  if (verbose)
    message("[uncorrected] cell-name form: ", sum(use_long), " with region suffix, ",
            sum(use_short), " without")

  dirs <- list.dirs(region_dir(region), recursive = FALSE, full.names = FALSE)
  genes <- rownames(obj)
  out <- vector("list", length(unique(sids)))
  names(out) <- unique(sids)

  for (sid in unique(sids)) {
    hit <- dirs[startsWith(dirs, paste0(sid, "_"))]
    if (length(hit) != 1L)
      stop("cannot resolve a unique folder for sample_ids '", sid, "' in ",
           region_dir(region), " - found: ", paste(hit, collapse = ", "))
    f <- file.path(region_dir(region), hit, paste0("raw_", hit, ".rds"))
    if (!file.exists(f)) stop("missing raw object: ", f)

    raw <- readRDS(f)
    if (!"RAW" %in% names(raw@assays))
      stop("no RAW assay in ", f, " - assays: ", paste(names(raw@assays), collapse = ", "))
    m <- SeuratObject::LayerData(raw, assay = "RAW", layer = "counts")

    want <- bcs[sids == sid]
    miss <- setdiff(want, colnames(m))
    if (length(miss))
      stop(length(miss), " cell(s) of sample ", sid, " are absent from ", basename(f),
           " (e.g. ", miss[1], ") - barcode mapping is wrong, refusing to run DE")

    g_have <- intersect(genes, rownames(m))
    sub <- m[g_have, want, drop = FALSE]
    if (length(g_have) < length(genes)) {
      pad <- Matrix::Matrix(0, nrow = length(setdiff(genes, g_have)), ncol = ncol(sub),
                            sparse = TRUE,
                            dimnames = list(setdiff(genes, g_have), colnames(sub)))
      sub <- rbind(sub, pad)[genes, , drop = FALSE]
      if (verbose) message("[uncorrected] ", sid, ": ", length(genes) - length(g_have),
                           " gene(s) absent from RAW, zero-filled")
    } else sub <- sub[genes, , drop = FALSE]

    colnames(sub) <- cells[sids == sid]      # back to the object's cell names
    out[[sid]] <- sub
    rm(raw, m); invisible(gc(FALSE))
    if (verbose) message("[uncorrected] ", sid, ": ", ncol(sub), " cells")
  }

  mat <- do.call(cbind, out)
  mat <- mat[, cells, drop = FALSE]          # exact cell order of the object
  stopifnot(identical(colnames(mat), colnames(obj)),
            identical(rownames(mat), rownames(obj)))
  if (verbose) message("[uncorrected] assembled ", nrow(mat), " genes x ", ncol(mat),
                       " cells from the RAW assay (uncorrected CellRanger counts)")
  mat
}

#' Switch muscat::pbDS(method = "edgeR") to edgeR's pre-4.0 quasi-likelihood fit.
#'
#' edgeR 4 changed glmQLFit's default method (legacy = FALSE). In the
#' cross-region design (90 samples, six region x condition means) it returns a
#' NEGATIVE F and p = 1 for astrocyte SERPINA3, whose PWoH counts are ~0 in INS
#' and PFC; legacy = TRUE gives F = 92.9 and the published run (older edgeR)
#' F = 108 on matching counts. pbDS() does not expose
#' `legacy`, but muscat imports glmQLFit and calls it unqualified inside .edgeR,
#' so rebinding that import changes exactly that call. enable = FALSE restores
#' the original binding.
edger_ql_legacy <- function(enable = TRUE) {
  imp <- parent.env(asNamespace("muscat"))
  if (!exists("glmQLFit", envir = imp, inherits = FALSE))
    stop("muscat does not import glmQLFit - cannot switch the QL method")
  orig <- getOption("scorch.glmQLFit_orig", get("glmQLFit", envir = imp))
  options(scorch.glmQLFit_orig = orig)
  new <- if (enable) function(...) edgeR::glmQLFit(..., legacy = TRUE) else orig
  unlockBinding("glmQLFit", imp)
  assign("glmQLFit", new, envir = imp)
  lockBinding("glmQLFit", imp)
  message("[DE] edgeR glmQLFit: ", if (enable) "legacy = TRUE (pre-4.0 QL method)" else "edgeR default")
  invisible(enable)
}

#' Negative-F fallback for a pbDS(method = "edgeR") result.
#'
#' Every gene keeps edgeR 4's default QL test. Only rows whose default F is
#' negative (p = 1, the degenerate case - e.g. cross-region astrocyte SERPINA3)
#' are refit: glmQLFit(legacy = TRUE), or glmLRT where legacy is negative too.
#' Works on the pbDS result before resDS() rounds it, and refits from pbDS's own
#' filtered DGEList per cell type (res$data[[k]]: samples, genes, normalisation
#' and dispersions exactly as in the default fit). Before swapping anything it
#' re-derives the default F from that object and stops unless it matches.
#' Adds `test` = "QL" | "QL_legacy" | "LRT" (F is NA for LRT rows) and
#' recomputes p_adj.loc per cell type and p_adj.glb across cell types (BH, as
#' muscat does).
pbds_negF_fallback <- function(res, design, contrast, verbose = TRUE) {
  for (cn in names(res$table)) {
    tabs <- res$table[[cn]]
    ctr  <- contrast[, cn]
    for (k in names(tabs)) {
      t <- as.data.frame(tabs[[k]]); t$test <- "QL"
      bad <- which(!is.na(t$F) & t$F < 0)
      if (length(bad)) {
        y <- res$data[[k]]
        d <- design[colnames(y), , drop = FALSE]
        q0 <- edgeR::glmQLFTest(edgeR::glmQLFit(y, d, legacy = FALSE), contrast = ctr)$table
        dev <- max(abs(q0[t$gene, "F"] - t$F) / pmax(1, abs(t$F)))
        if (!is.finite(dev) || dev > 1e-6)
          stop("negF fallback: refit does not reproduce the pbDS fit for ", k,
               " (max relative difference in F ", signif(dev, 3), ")")
        q1 <- edgeR::glmQLFTest(edgeR::glmQLFit(y, d, legacy = TRUE), contrast = ctr)$table
        ok <- q1[t$gene[bad], "F"] >= 0
        i1 <- bad[ok]; i2 <- bad[!ok]
        if (length(i1)) {
          g <- t$gene[i1]
          t$logFC[i1] <- q1[g, "logFC"]; t$logCPM[i1] <- q1[g, "logCPM"]
          t$F[i1] <- q1[g, "F"]; t$p_val[i1] <- q1[g, "PValue"]; t$test[i1] <- "QL_legacy"
        }
        if (length(i2)) {
          lr <- edgeR::glmLRT(edgeR::glmFit(y, d), contrast = ctr)$table
          g <- t$gene[i2]
          t$logFC[i2] <- lr[g, "logFC"]; t$logCPM[i2] <- lr[g, "logCPM"]
          t$F[i2] <- NA_real_; t$p_val[i2] <- lr[g, "PValue"]; t$test[i2] <- "LRT"
        }
        t$p_adj.loc <- p.adjust(t$p_val, method = "BH")
        if (verbose) message("[negF] ", k, ": ", length(bad), " row(s) with F < 0 -> ",
                             length(i1), " legacy QL, ", length(i2), " LRT")
      }
      tabs[[k]] <- t
    }
    pa  <- p.adjust(unlist(lapply(tabs, function(u) u$p_val), use.names = FALSE), method = "BH")
    grp <- rep(seq_along(tabs), vapply(tabs, nrow, integer(1)))
    for (i in seq_along(tabs)) tabs[[i]]$p_adj.glb <- pa[grp == i]
    res$table[[cn]] <- tabs
  }
  res
}

#' Which cross-region DE table the downstream figures read.
#'
#' The cross-region design has up to three samples (INS, PFC, VST) per donor, so
#' samples are not independent. The primary cross-region model is donor-aware:
#' limma-voom with duplicateCorrelation(block = donor). The edgeR fit from
#' 03-DE_analysis/07-cross_region_edgeR.R, which treats samples as independent
#' as in the published analysis, is kept as the concordance check. Regional DE
#' (one sample per donor) remains edgeR.
#'
#'   SCORCH_XR_DE=edgeR        (default) data/all_HIV-CTR_res_edgeR_filtered_withFreq<sfx>.RDS
#'   SCORCH_XR_DE=donor_aware  data/all_HIV-CTR_res_donorAware_withFreq.RDS, built by
#'                             revision/tools/cross_region_donor_aware_table.R from the
#'                             donor-aware fit, in the edgeR table's columns so the
#'                             downstream scripts need no other change
#' XR_OUT_SFX is appended to every figure/table name, so the two sets never overwrite
#' each other. The donor-aware table exists for uncorrected counts only.
XR_DE <- Sys.getenv("SCORCH_XR_DE", "edgeR")
stopifnot(XR_DE %in% c("edgeR", "donor_aware"))
XR_OUT_SFX <- if (XR_DE == "donor_aware") "_donor_aware" else ""
xr_de_file <- function(sfx = "", dir = file.path(OUT_ROOT, "03-DE_analysis", "cross_region", "data")) {
