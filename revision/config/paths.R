#' Display labels for HIV status: PWH / PWoH, never HIV / CTR.
#'
#' The stored values in `condition_new` are "HIV"/"CTR" and the DE design and
#' contrast names depend on them, so they are not renamed in the data. This maps
#' them for display only (figure legends, facet strips, printed tables), so the
#' terminology is person-first everywhere the reader sees it while the modelling
#' code keeps working.
PWH_LEVELS <- c("PWoH", "PWH")
pwh_relabel <- function(x) {
  x <- as.character(x)
  out <- ifelse(x %in% c("HIV", "HIV+", "PWH", "TRUE", "True"), "PWH",
         ifelse(x %in% c("CTR", "CTRL", "Control", "PWoH", "FALSE", "False"), "PWoH", x))
  factor(out, levels = union(PWH_LEVELS, setdiff(unique(out), PWH_LEVELS)))
}
