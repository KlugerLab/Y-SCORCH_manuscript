# ---- group detection frequencies, BY CONDITION --------------------------------
## The published DE and ATAC-DE scripts computed avg_CTR_frq / avg_HIV_frq as
## mean(c_across(<firstsample>.frq:<lastsample>.frq)), a column range that
## encodes the published sample order. When the sample set or its
## order changes, the range spans the wrong samples and still returns plausible
## numbers. These averages drive the > 5% expression filter used by the pathway
## figures, so a wrong range silently changes which genes are shown.
## Maps each .frq column to its condition via the experiment_info prepSCE built.
add_group_frq <- function(res, sce, region) {
  ei   <- as.data.frame(S4Vectors::metadata(sce)$experiment_info)
  frq  <- grep("\\.frq$", colnames(res), value = TRUE)
  ## undo the "a" prefix the scripts add to ids that start with a digit
  sid  <- sub("^a(?=[0-9])", "", sub("\\.frq$", "", frq), perl = TRUE)
  ## resDS(frq = TRUE) also appends group-level columns, "CTR.frq" and
  ## "HIV.frq", after the per-sample ones. They are not samples and must not be
  ## averaged in.
  is_sample <- sid %in% as.character(ei$sample_id)
  if (any(!is_sample))
    message("[frq] ", region, ": ignoring non-sample columns: ",
            paste(frq[!is_sample], collapse = ", "))
  frq <- frq[is_sample]; sid <- sid[is_sample]
  ## every sample in the design should have exactly one column
  if (length(unique(sid)) != nrow(ei))
    stop("[frq] ", region, ": ", length(unique(sid)), " sample .frq columns for ",
         nrow(ei), " samples in the design")
  cond <- setNames(as.character(ei$group_id), as.character(ei$sample_id))[sid]
  if (!any(cond == "CTR") || !any(cond == "HIV"))
    stop("[frq] a condition has no .frq columns - check group_id levels")
  res <- as.data.frame(res)
  res$avg_CTR_frq <- rowMeans(res[, frq[cond == "CTR"], drop = FALSE], na.rm = TRUE)
  res$avg_HIV_frq <- rowMeans(res[, frq[cond == "HIV"], drop = FALSE], na.rm = TRUE)
  res$region <- region
  message("[frq] ", region, ": ", sum(cond == "CTR"), " PWoH / ",
          sum(cond == "HIV"), " PWH columns, mapped by condition")
  res
}

## Cross-region variant of add_group_frq(), for 07-cross_region_edgeR.R.
## The published script averaged six positional column
## ranges (e.g. c_across(VST.10280.frq:VST.1059.frq)), one per region x
## condition, then took the mean of the three regional averages. Here each
## per-sample column (sample ids are "<REGION>.<sample_ids>") is mapped to its
## group_id ("<REGION>.<CTR|HIV>") via experiment_info; group-level columns that
## resDS(frq = TRUE) appends are skipped. Output columns and the final averaging
## are the published ones: avg_<COND>_<REGION>_frq, then avg_CTR_frq / avg_HIV_frq
## as the row mean of the three regional averages.
add_group_frq_by_region <- function(res, sce) {
  ei  <- as.data.frame(S4Vectors::metadata(sce)$experiment_info)
  frq <- grep("\\.frq$", colnames(res), value = TRUE)
  sid <- sub("\\.frq$", "", frq)
  is_sample <- sid %in% as.character(ei$sample_id)
  if (any(!is_sample))
    message("[frq] cross-region: ignoring non-sample columns: ",
            paste(frq[!is_sample], collapse = ", "))
  frq <- frq[is_sample]; sid <- sid[is_sample]
  if (length(unique(sid)) != nrow(ei))
    stop("[frq] cross-region: ", length(unique(sid)), " sample .frq columns for ",
         nrow(ei), " samples in the design")
  grp <- setNames(as.character(ei$group_id), as.character(ei$sample_id))[sid]
  res <- as.data.frame(res)
  for (g in sort(unique(grp))) {
    reg <- sub("\\..*$", "", g); cond <- sub("^.*\\.", "", g)
    nm  <- sprintf("avg_%s_%s_frq", cond, reg)
    res[[nm]] <- rowMeans(res[, frq[grp == g], drop = FALSE], na.rm = TRUE)
    message("[frq] ", nm, ": ", sum(grp == g), " samples")
  }
  for (cond in c("CTR", "HIV")) {
    cols <- grep(sprintf("^avg_%s_(INS|PFC|VST)_frq$", cond), names(res), value = TRUE)
    res[[sprintf("avg_%s_frq", cond)]] <- rowMeans(res[, cols, drop = FALSE], na.rm = TRUE)
  }
  res
}
