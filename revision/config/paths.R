#' Create an output directory under OUT_ROOT and setwd() into it.
#' Replaces the published scripts' hardcoded `setwd(wd)`, so every
#' downstream relative write ("./data/...", "./figures/...") lands in OUT_ROOT
#' with no further edits to the script body.
rerun_setup <- function(stage, subdirs = character()) {
  wd <- file.path(OUT_ROOT, stage)
  dir.create(wd, recursive = TRUE, showWarnings = FALSE)
  for (d in subdirs) {
    dir.create(file.path(wd, d), recursive = TRUE, showWarnings = FALSE)
  }
  setwd(wd)

  ## Stray plots: 8 of the published plotting scripts open no graphics device, so
  ## under Rscript every DimPlot/DotPlot lands in an unnamed Rplots.pdf. Open a
  ## PDF named for the running script instead, so they are attributable.
  ## Named figures still come from save_embedding_panels() and the scripts' own
  ## png()/ggsave() calls.
  args <- commandArgs(trailingOnly = FALSE)
  fa <- sub("^--file=", "", args[grep("^--file=", args)])
  if (length(fa) == 1L) {
    dir.create(file.path(wd, "figures"), recursive = TRUE, showWarnings = FALSE)
    out <- file.path(wd, "figures",
                     paste0(tools::file_path_sans_ext(basename(fa)), "_unnamed_plots.pdf"))
    grDevices::pdf(out, width = 10, height = 8, onefile = TRUE)
    reg.finalizer(globalenv(), function(e) try(grDevices::dev.off(), silent = TRUE),
                  onexit = TRUE)
    message("[rerun] stray plots -> ", out)
  }

  message("[rerun] wd = ", wd)
  invisible(wd)
}

## ---- Write guards -----------------------------------------------------------
## The published scripts assume their output directories already exist. In a
## fresh output tree they may not, and R's writers fail only when called, which
## for saveRDS is often the last line of a long script (e.g. combined/01, after
## hours of t-SNE and UMAP).
##
## These shadow the base writers and create the parent directory first.
saveRDS <- function(object, file = "", ...) {
  d <- dirname(file)
  if (nzchar(d) && d != "." && !dir.exists(d)) {
    dir.create(d, recursive = TRUE, showWarnings = FALSE)
    message("[rerun] created output dir: ", d)
  }
  base::saveRDS(object, file = file, ...)
}

write.csv <- function(x, file = "", ...) {
  if (is.character(file) && nzchar(file)) {
    d <- dirname(file)
    if (nzchar(d) && d != "." && !dir.exists(d)) dir.create(d, recursive = TRUE, showWarnings = FALSE)
  }
  utils::write.csv(x, file = file, ...)
}

#' Insert the active output suffix before a file extension.
#'
#' Set with options(scorch.out_suffix = "_corrected"). Used so the corrected DE
#' figures land beside the primary ones instead of overwriting them. Rewriting
#' every path at the call site is not reliable: the scripts build filenames in
#' many shapes (png(filename = paste0(dir, var, "_up.png")), png(file = "x.png"),
#' ggsave()), and a regex over them misses cases. Doing it in the writers below
#' catches every one.
.sfx_path <- function(p) {
  s <- getOption("scorch.out_suffix", "")
  if (!nzchar(s) || !is.character(p) || !length(p) || !nzchar(p[1])) return(p)
  ext <- regmatches(p, regexpr("\\.[A-Za-z0-9]+$", p))
  if (!length(ext) || !nzchar(ext)) return(paste0(p, s))
  base <- sub("\\.[A-Za-z0-9]+$", "", p)
  if (endsWith(base, s)) return(p)          # already suffixed at the call site
  paste0(base, s, ext)
}

png <- function(filename = "", ...) {
  filename <- .sfx_path(filename)
  d <- dirname(filename)
  if (nzchar(d) && d != "." && !dir.exists(d)) dir.create(d, recursive = TRUE, showWarnings = FALSE)
  grDevices::png(filename = filename, ...)
}

pdf <- function(file = "", ...) {
  file <- .sfx_path(file)
  d <- dirname(file)
  if (nzchar(d) && d != "." && !dir.exists(d)) dir.create(d, recursive = TRUE, showWarnings = FALSE)
  grDevices::pdf(file = file, ...)
}

ggsave <- function(filename, ...) {
  filename <- .sfx_path(filename)
  d <- dirname(filename)
  if (nzchar(d) && d != "." && !dir.exists(d)) dir.create(d, recursive = TRUE, showWarnings = FALSE)
  ggplot2::ggsave(filename = filename, ...)
}

#' Fraction of cells per cluster expressing each gene — layer-aware.
#'
#' During integration the RNA assay is split into one counts layer per sample
#' (counts.10280, counts.1068, ...). LayerData(layer = "counts") then returns
#' only the FIRST layer, with a warning rather than an error, so any downstream
#' per-cell computation silently runs on a subset and fails on a length mismatch.
#' JoinLayers() is not an option here: the script still needs the split layers for
#' re-integration. This walks the layers and assembles the per-cell result.
#'
#' combine = "mean" averages the per-gene fractions across the panel; "max" takes
#' the single best-detected marker. "mean" is the default because the VST
#' excitatory rule in VST/03 was calibrated against the published object under it
#' — do not change that default without recalibrating VST/03.
#'
#' "mean" is only meaningful for a panel whose members have comparable detection
#' rates. Mixing a near-universal marker with a sparse one (MBP with MOG) or with
#' one that is absent from the object entirely drags the panel down by a constant
#' factor, and a threshold set on the result is measuring the panel's composition
#' as much as the biology. Genes absent from the object are dropped with a
#' warning rather than silently counted as zero in every cell.
cluster_pct_expressing <- function(obj, genes, group = "seurat_clusters",
                                   assay = "RNA", combine = c("mean", "max")) {
  combine <- match.arg(combine)
  g <- intersect(genes, rownames(obj[[assay]]))
  if (!length(g)) stop("none of the requested genes are present: ",
                       paste(utils::head(genes), collapse = ", "))
  absent <- setdiff(genes, g)
  if (length(absent))
    warning("cluster_pct_expressing: dropping gene(s) absent from the object: ",
            paste(absent, collapse = ", "), call. = FALSE)
  lyrs <- SeuratObject::Layers(obj[[assay]], search = "counts")
  if (!length(lyrs)) stop("no counts layer in assay ", assay)

  expressed <- vector("list", length(lyrs))
  for (i in seq_along(lyrs)) {
    m <- SeuratObject::LayerData(obj, assay = assay, layer = lyrs[i])
    keep <- intersect(g, rownames(m))
    e <- matrix(FALSE, nrow = length(g), ncol = ncol(m),
                dimnames = list(g, colnames(m)))
    if (length(keep)) e[keep, ] <- as.matrix(m[keep, , drop = FALSE] > 0)
    expressed[[i]] <- e
  }
  E <- do.call(cbind, expressed)

  grp <- obj@meta.data[[group]]
  names(grp) <- rownames(obj@meta.data)
  grp <- as.character(grp[colnames(E)])
  if (anyNA(grp)) stop("cells in the counts layers are missing from meta.data")

  out <- t(apply(E, 1, function(v) tapply(v, grp, mean)))
  if (length(g) == 1) out <- matrix(out, nrow = 1, dimnames = list(g, names(tapply(E[1, ], grp, mean))))
  if (combine == "max") apply(out, 2, max) else colMeans(out)
}

#' Per-gene fraction expressing: genes x clusters, no collapsing.
#'
#' The matrix cluster_pct_expressing() collapses. Returned separately so a
#' criterion can be re-derived from saved numbers without reloading a 4 GB
#' object, and so per-gene detection rates are visible rather than buried.
cluster_gene_pct <- function(obj, genes, group = "seurat_clusters", assay = "RNA") {
  g <- intersect(genes, rownames(obj[[assay]]))
  if (!length(g)) stop("none of the requested genes are present")
  lyrs <- SeuratObject::Layers(obj[[assay]], search = "counts")
  if (!length(lyrs)) stop("no counts layer in assay ", assay)
  chunks <- lapply(lyrs, function(l) {
    m <- SeuratObject::LayerData(obj, assay = assay, layer = l)
    keep <- intersect(g, rownames(m))
    e <- matrix(FALSE, nrow = length(g), ncol = ncol(m), dimnames = list(g, colnames(m)))
    if (length(keep)) e[keep, ] <- as.matrix(m[keep, , drop = FALSE] > 0)
    e
  })
  E <- do.call(cbind, chunks)
  grp <- obj@meta.data[[group]]
  names(grp) <- rownames(obj@meta.data)
  grp <- as.character(grp[colnames(E)])
  if (anyNA(grp)) stop("cells in the counts layers are missing from meta.data")
  t(apply(E, 1, function(v) tapply(v, grp, mean)))
}

#' Mean expression per cluster, z-scored across clusters, with cluster names
#' that actually match the metadata.
#'
#' Seurat's AverageExpression() prefixes numeric identities with "g" — cluster 22
#' comes back as "g22". Matching those against seurat_clusters silently finds
#' nothing: cluster-level calls look fine while zero cells get flagged, and any
#' table()/tapply() lookup keyed on them returns NA. Strips the prefix and
#' verifies the names resolve.
cluster_avg_z <- function(obj, features, group = "seurat_clusters", assay = "RNA") {
  have <- intersect(features, rownames(obj))
  if (length(have) < 2) stop("too few marker genes present: ", length(have))
  m <- Seurat::AverageExpression(obj, features = have, group.by = group,
                                 assays = assay, layer = "data")[[assay]]
  m <- as.matrix(m)
  lv <- levels(factor(obj@meta.data[[group]]))
  cn <- colnames(m)
  if (!all(cn %in% lv) && all(sub("^g", "", cn) %in% lv)) cn <- sub("^g", "", cn)
  colnames(m) <- cn
  if (!all(colnames(m) %in% lv)) {
    stop("cluster names from AverageExpression do not match ", group, ": ",
         paste(utils::head(setdiff(colnames(m), lv)), collapse = ", "))
  }
  z <- t(scale(t(m)))
  z[is.na(z)] <- 0            # genes with zero variance across clusters
  z
}

#' Save named tSNE / UMAP panels for one object.
#'
#' The published scripts call DimPlot() with no graphics device open. Under
#' RStudio the plots went to the pane; under Rscript they all land unlabelled and
#' in call order in a single Rplots.pdf. This writes explicit, named files so the
#' embedding figures can actually be found and compared.
save_embedding_panels <- function(obj, prefix, dir = "./figures/embeddings",
                                  reductions = c("tsne", "umap"),
                                  group_bys = c("consensus_annotation_v2",
                                                "consensus_annotation_v3",
                                                "consensus_cell_type_coarse_l1",
                                                "seurat_clusters", "sample_ids",
                                                "condition_new", "region")) {
  dir.create(dir, recursive = TRUE, showWarnings = FALSE)
  have_red <- intersect(reductions, names(obj@reductions))
  have_grp <- intersect(group_bys, colnames(obj@meta.data))
  n <- 0L
  for (red in have_red) {
    for (g in have_grp) {
      pl <- Seurat::DimPlot(obj, reduction = red, group.by = g,
                            label = !(g %in% c("sample_ids", "condition_new")),
                            raster = FALSE, shuffle = TRUE,
                            label.size = 5, pt.size = 0.5)
      f <- file.path(dir, paste0(prefix, "_", red, "_",
                                 gsub("[^A-Za-z0-9]+", "_", g), ".png"))
      ggplot2::ggsave(f, pl, width = 11, height = 9, dpi = 150)
      n <- n + 1L
    }
  }
  message("[figures] ", prefix, ": wrote ", n, " panels (",
          paste(have_red, collapse = "+"), ") to ", dir)
  invisible(n)
}

#' Run UMAP with real threading, restoring the previous future plan afterwards.
run_umap_threaded <- function(obj, reduction = "harmony", dims = 1:50,
                              seed.use = 3, threads = UMAP_THREADS) {
  old <- future::plan()
  on.exit(future::plan(old), add = TRUE)
  future::plan(future::multicore, workers = threads)
  Seurat::RunUMAP(obj, reduction = reduction, dims = dims, seed.use = seed.use,
                  reduction.name = "umap", reduction.key = "UMAP_")
}

#' Give every per-sample metadata table the same columns, in the same order.
#'
#' The corrected pipeline writes a DIFFERENT column set per sample: it drops
#' subject-metadata (*_v2) fields that are empty for that subject. Across INS
#' that is 22 distinct signatures over 31 samples, 116-136 columns each, so
#' `do.call(cbind, sce.list)` fails with
#'   "the DFrame objects to combine must have the same column names".
#' The original 240610 pipeline had one signature of 147 columns for all 53
#' samples, so the published scripts never had to handle this.
#'
#' Missing columns are filled with NA rather than intersected away: the union is
#' 149 columns against the original's 147, so this reconstructs what the original
#' metadata looked like. Every analysis-critical column (percent.mt,
#' seurat_clusters, cell2remove_highMT, sample_name, sample_ids, the predicted
#' ids and all 55 prediction-score columns) is already present in all samples, so
#' nothing load-bearing depends on the fill.
align_coldata <- function(dfs) {
  all_cols <- unique(unlist(lapply(dfs, names)))
  lapply(dfs, function(d) {
    for (m in setdiff(all_cols, names(d))) d[[m]] <- NA
    d[, all_cols, drop = FALSE]
  })
}

#' Load the rebuilt sample sheet, filtered the way the original scripts filter it.
